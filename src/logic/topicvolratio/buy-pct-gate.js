/**
 * 买点侧「9:26 竞价口径」门控判据（纯函数，§15 可单测）。
 *
 * ★★ [BUY-PCT-GATE 2026-10-31 用户口径]
 *
 * 用户报障（逐字）：
 *   「题材量比那里10月30日，打开时，出现上海九百和文投控股这两只票，后面文投控股又自动显示，
 *     我希望刚开始就显示正确的上海九百，文投控股如果不符合，最好不要显示出来，
 *     如果网络有延迟的话，很容易买错票。」
 *
 * 🔴【根因】买点侧选股 = 「组内十日涨幅降序 ⇒ 龙位 ⇒ 取龙一/龙二…」，而这份十日涨幅有两套口径：
 *   · 【9:26 竞价口径】= 用户要的那一套（早上 9:26 那一刻选中的票，任何时候翻回来都是同一批），
 *     由 `logic/auction/range-auction-leg.js#readAuctionLegRangeMap(date)` **异步**读库反解；
 *   · 【收盘口径】= 内存里现成的那一份（`rec.dragonMap`）。
 *   口径还没读回来时，规则层 `buyDragonMap = o.buyDragonMap || dragonMap` 会先拿收盘口径算一遍并上屏；
 *   收盘后 T 腿已被换成收盘涨幅 ⇒ 组内重排 ⇒ 龙位变 ⇒ **同一题材选出另一只票** ⇒ 屏幕上换票。
 *   其余选股输入（题材排名 = 平均竞价量比、竞价一字 / 连续停牌名单、题材块成员、只数）全是同步的，
 *   首帧之后不会变 ⇒ 「先两只、后换掉一只」只可能来自这一处。
 *
 * ✅ 判据（与 [DIVERGE-GATE 2026-10-21] 同一条口径：结论没落地就【先不显示结论】）：
 *   该展示日的 9:26 口径【还没落地】⇒ 买点侧先不出票。
 *
 * ⚠️ 两条容易被「优化」掉的细节，⛔ 别改：
 *   ① **只认「日期对得上」的那份**：切日期那一帧 `resolvedDate` 还是旧日期，必须继续挂占位。
 *      ⛔ 写成 `if (!resolvedDate) return true` 会把 A 日的口径当 B 日用 —— §10 红线。
 *   ② **读过就算落地**：`resolvedDate === date` 既可能是读成功（用 9:26 口径），也可能是读失败
 *      （已按既有降级用当前口径，且说明区会如实标「9:26 口径未就绪」）。
 *      ⇒ ⛔ 不要在这里区分成功/失败：那会让一次读失败把买点侧永久锁死。
 *
 * @param {{date?:string, resolvedDate?:string}} ctx
 *        date         = 当前展示日（YYYY-MM-DD）
 *        resolvedDate = 最近一次「读过」9:26 口径的日期（成功或失败都算读过）
 * @returns {boolean} true = 口径未就绪 ⇒ 买点侧先不显示选票
 */
export function isBuyPctPending(ctx) {
  const o = ctx || {};
  const d = String(o.date || '').trim();
  const resolved = String(o.resolvedDate || '').trim();
  // 没有展示日 ⇒ 这张看板本来就没在算（空态由别处的「未就绪」负责）⇒ 本门控不管
  if (!d) return false;
  return resolved !== d;
}
