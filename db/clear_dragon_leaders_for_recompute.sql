--
-- 背景（2026-09-14 修正 commit）：
--   旧实现用【第二页题材分类】(getTopicGroups) 分组 —— 一只股票命中的所有核心词都会建组，
--   同一只票会同时出现在多个题材里 → 它可能当上「自己并不属于的那个题材」的龙头，
--   于是次日龙头组里冒出多余的人。
--   用户实测：9/11 题材 toggle 里「大消费」龙一=国芳集团 96.04%、龙二=桂林旅游 60.23%，
--   但 9/14 龙头组里桂林旅游也在（它按第二页口径另属某个题材并成了那个题材的龙头）。
--   已改为复用题材 toggle 的分类（getPrimaryTopicMap + classifyStockPrimaryTopic）：
--   一只票只归一个主题材 → 一个题材只有一只龙头，且「其它」不参与评选。
--
-- 为什么必须手动清一次：
--   代码修好后，评选只在「该评选日名册为空」时才会补算（self-heal，避免每次加载都重算/重写）。
--   9/11 的名册已经存在（旧口径写入），不满足补算条件 → 旧行会一直残留、
--   且「同名不同题材」的旧行也不会被 upsert 覆盖掉（upsert 键是 (date, topic)）。
--
-- 安全性：
--   · dragon_leaders 是【纯派生数据】：全部由前端按题材 + 十日区间涨幅算出来，没有任何人工录入；
--   · 清空后不会丢信息 —— 只要打开对应日期（D 的龙头组读 prevTradingDay(D) 的名册），
--     前端就会自动补评选并落库（读取 stock_range_pct 云端权威值，0 猫抓额度）；
--   · 反向风险极低：清空后最多是「龙头组暂时为空」，不会影响任何其它看板。
--
-- 执行方式：Supabase Dashboard -> SQL Editor -> 新建 Query -> Run
-- ============================================================================

